def lookup_iata_code(query: str) -> Optional[str]:
    """
    Look up a 3-letter IATA code from the static airport dictionary.
    Returns None if not found, allowing caller to fall back to dynamic LLM resolution.
    """
    if not query:
        return None
    clean = query.strip()
    # 3-letter uppercase check
    if len(clean) == 3 and clean.isalpha() and clean.isupper():
        return clean
    norm = clean.lower()
    if norm in AIRPORT_LOOKUP:
        return AIRPORT_LOOKUP[norm]
    # Check city if "City, Country" format provided
    if "," in norm:
        city_part = norm.split(",")[0].strip()
        if city_part in AIRPORT_LOOKUP:
            return AIRPORT_LOOKUP[city_part]
    # Check simple punctuation / prefix stripped
    stripped = norm.replace("-", " ").replace("'", "").replace(",", "").strip()
    if stripped in AIRPORT_LOOKUP:
        return AIRPORT_LOOKUP[stripped]
    return None
